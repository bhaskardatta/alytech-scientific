/**
 * Astro integration, Cloudflare build only (astro.config.mjs): writes dist/client/_headers and _redirects, the Workers static-assets
 * equivalents of the headers/redirects in vercel.json. vercel.json stays the ONE place to edit them, so the two hosts cannot drift.
 * (Generated rather than kept in public/ so the Vercel build does not publish them as /_headers and /_redirects.)
 *
 * Applies to static files only. Responses the Worker generates (pages under /admin, /api, /ingest ...) get the same security
 * headers from src/worker.ts, which reads the same vercel.json block.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Fingerprinted build output; the adapter would add this too, stated here so it is visible next to the other cache rules.
const IMMUTABLE = 'public, max-age=31536000, immutable';
const NOINDEX = 'noindex, nofollow';
const ADMIN_HOST = 'admin.alytechme.com'; // keep in step with the ADMIN_HOST secret (docs/cloudflare-go-live.md)

/** Vercel path pattern ("/images/(.*)") -> Workers pattern ("/images/*"). Anything fancier is refused rather than guessed. */
const toPattern = (source) => {
  const p = source.replace(/\(\.\*\)$/, '*');
  if (/[()]/.test(p)) throw new Error(`cloudflare/assets-rules: cannot translate vercel.json source "${source}"`);
  return p;
};

export function rulesFromVercel(vercel) {
  const headers = [];
  for (const h of vercel.headers ?? []) {
    if (h.has) continue; // the *.vercel.app noindex rule; the workers.dev equivalent is below
    headers.push([toPattern(h.source), h.headers.map(({ key, value }) => `${key}: ${value}`)]);
  }
  // Workers preview/production URLs (name.subdomain.workers.dev and version-name.subdomain.workers.dev) must not be indexed.
  // Host placeholders match one DNS label each (https://developers.cloudflare.com/workers/static-assets/headers/).
  headers.push(['https://:worker.:subdomain.workers.dev/*', [`X-Robots-Tag: ${NOINDEX}`]]);
  headers.push(['https://:version.:worker.:subdomain.workers.dev/*', [`X-Robots-Tag: ${NOINDEX}`]]);
  // The admin host also serves the public files (/about/ ...) because they are plain assets; none of it should be indexed there.
  headers.push([`https://${ADMIN_HOST}/*`, [`X-Robots-Tag: ${NOINDEX}`]]);
  headers.push(['/_astro/*', [`Cache-Control: ${IMMUTABLE}`]]);

  const headersFile = [
    '# Generated by cloudflare/assets-rules.mjs from vercel.json at build time. Do not edit.',
    ...headers.map(([pattern, lines]) => `${pattern}\n${lines.map((l) => `  ${l}`).join('\n')}`),
    '',
  ].join('\n');

  const redirectsFile = [
    '# Generated by cloudflare/assets-rules.mjs from vercel.json at build time. Do not edit.',
    ...(vercel.redirects ?? []).map((r) => `${r.source} ${r.destination} ${r.statusCode ?? 301}`),
    '',
  ].join('\n');

  return { headersFile, redirectsFile };
}

export default function assetsRules() {
  let root;
  let clientDir;
  return {
    name: 'alytech:cloudflare-assets-rules',
    hooks: {
      'astro:config:done': ({ config }) => {
        root = config.root;
        clientDir = config.build.client;
      },
      'astro:build:done': () => {
        const vercel = JSON.parse(readFileSync(new URL('./vercel.json', root), 'utf8'));
        const { headersFile, redirectsFile } = rulesFromVercel(vercel);
        const headersPath = fileURLToPath(new URL('./_headers', clientDir));
        const redirectsPath = fileURLToPath(new URL('./_redirects', clientDir));
        writeFileSync(headersPath, headersFile);
        // Keep anything the adapter appended for Astro-level redirect routes (none today).
        const old = existsSync(redirectsPath) ? readFileSync(redirectsPath, 'utf8').split('\n') : [];
        writeFileSync(redirectsPath, redirectsFile + old.filter((l) => l && !l.startsWith('#') && !redirectsFile.includes(l)).map((l) => `${l}\n`).join(''));
      },
    },
  };
}
